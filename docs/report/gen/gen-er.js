// Draws the Chen-notation ER diagrams (TikZ) from er-model.js and er-layout.js, after checking the
// model against the live schema dump: every foreign key (except fk_ctx_*) is exactly one
// relationship, participation matches nullability, and every cross-module relationship is drawn
// in a diagram of each module it joins. Usage: node gen-er.js <schema.json> <out-dir>
const fs = require('fs');
const path = require('path');
const { MODULES, ENTITIES, RELS } = require('./er-model');
const LAYOUT = require('./er-layout');

const [schemaFile = path.join(__dirname, '../data/schema.json'), outDir = path.join(__dirname, '../figures/er')] = process.argv.slice(2);
const d = JSON.parse(fs.readFileSync(schemaFile, 'utf8'));
const fail = (m) => { console.error('ER check: ' + m); process.exitCode = 1; };

// ---- checks against the schema
const tableOf = Object.fromEntries(Object.entries(ENTITIES).map(([e, v]) => [v.table, e]));
const fks = d.fks.filter(f => !f.name.startsWith('fk_ctx_'));
const seen = new Map();
for (const r of RELS) for (const fk of r.fks) {
  if (seen.has(fk)) fail(`${fk} in ${seen.get(fk)} and ${r.name}`); seen.set(fk, r.name);
  const [t, c] = fk.split('.');
  const f = fks.find(x => x.t === t && x.cols === c);
  if (!f) { fail(`${fk} (${r.name}) is not a foreign key`); continue; }
  if (!r.ends.some(e => e[0] === tableOf[f.rt])) fail(`${r.name}: ${fk} references ${f.rt}, not an end`);
  if (r.ends.length === 2 && !r.attrs.length) { // binary 1:N / 1:1: the child's participation is total iff NOT NULL
    const child = r.ends.find(e => ENTITIES[e[0]].table === t);
    const col = d.columns.find(x => x.t === t && x.name === c);
    if ((col.nullable === 'NO') !== (child[2] === 'total')) fail(`${r.name}: ${t}.${c} nullable=${col.nullable} but ${child[0]} is ${child[2]}`);
    const unique = d.indexes.some(i => i.t === t && !i.non_unique && i.cols === c);
    if ((child[1] === '1') !== unique) fail(`${r.name}: ${t}.${c} unique=${unique} but cardinality ${child[1]}`);
  }
}
for (const f of fks) if (!seen.has(`${f.t}.${f.cols}`)) fail(`foreign key ${f.t}.${f.cols} has no relationship`);
const base = d.tables.filter(t => t.type === 'BASE TABLE').map(t => t.name).filter(t => t !== 'schema_migrations');
const relTables = new Set(RELS.filter(r => r.fks.every(f => f.startsWith(r.fks[0].split('.')[0] + '.')) && r.fks.length > 1).map(r => r.fks[0].split('.')[0]));
for (const t of base) if (!tableOf[t] && !relTables.has(t)) fail(`table ${t} has no entity or relationship`);
for (const [e, v] of Object.entries(ENTITIES)) for (const a of v.attrs) {
  const names = a[1] === 'composite' ? a[2] : [a[0]];
  for (const n of names) if (!['age'].includes(n) && !d.columns.some(c => c.t === v.table && c.name === n)) fail(`${e}.${n} is not a column of ${v.table}`);
}
for (const r of RELS) for (const a of r.attrs) {
  const t = r.fks[0].split('.')[0];
  if (!d.columns.some(c => c.t === t && c.name === a)) fail(`${r.name} attribute ${a} is not a column of ${t}`);
}

// ---- which diagrams draw each relationship
const modulesOf = (r) => [...new Set(r.ends.map(e => ENTITIES[e[0]].module))];
const drawnIn = {};
for (const [id, L] of Object.entries(LAYOUT.diagrams)) for (const name of Object.keys(L.rels || {})) (drawnIn[name] ??= []).push(id);
for (const r of RELS) {
  const where = drawnIn[r.name] || [];
  if (!where.length) fail(`${r.name} is not drawn`);
  for (const m of modulesOf(r)) if (!where.some(id => LAYOUT.diagrams[id].module === m)) fail(`${r.name} joins module ${m} but is not drawn there`);
}

// ---- TikZ
const esc = (s) => String(s).replace(/_/g, '\\_');
const label = (a, kind) => kind === 'key' ? `\\underline{${esc(a)}}` : kind === 'partial' ? `\\dashuline{${esc(a)}}` : esc(a);
const attStyle = { key: 'att', partial: 'att', plain: 'att', derived: 'att,dashed', multi: 'att,double,double distance=0.8pt', composite: 'att' };
const pt = (p) => Array.isArray(p) ? `(${p[0]},${p[1]})` : `(${p})`;

function diagram(id, L) {
  const out = [`% Generated by docs/report/gen/gen-er.js: diagram ${id} (Module ${L.module})`, `\\begin{tikzpicture}[x=1cm,y=${L.yscale || 1}cm]`];
  const relsHere = RELS.filter(r => L.rels[r.name]);
  // entities: own (with attributes) and references
  for (const [e, spec] of Object.entries(L.entities)) {
    const E = ENTITIES[e]; if (!E) { fail(`${id}: unknown entity ${e}`); continue; }
    const pos = Array.isArray(spec) ? spec : spec.at;
    if (spec.ref) out.push(`\\node[refent] (${e}) at ${pt(pos)} {${esc(e)}\\\\[-1pt]{\\tiny see ${spec.see || 'Module ' + E.module}}};`);
    else {
      if (E.module !== L.module && !spec.ref) fail(`${id}: ${e} belongs to module ${E.module}; draw it as a reference`);
      out.push(`\\node[${E.weak ? 'weakent' : 'ent'}] (${e}) at ${pt(pos)} {${esc(e)}};`);
      for (const a of E.attrs) {
        const ap = spec.attrs?.[a[0]]; if (!ap) { fail(`${id}: no position for ${e}.${a[0]}`); continue; }
        const kind = a[1] || 'plain', aid = `${e}-${a[0]}`;
        out.push(`\\node[${attStyle[kind]}] (${aid}) at ${pt(ap)} {${label(a[0], kind)}};`, `\\draw (${aid}) -- (${e});`);
        if (kind === 'composite') for (const c of a[2]) {
          const cp = spec.attrs[`${a[0]}.${c}`]; if (!cp) { fail(`${id}: no position for ${e}.${a[0]}.${c}`); continue; }
          out.push(`\\node[att] (${aid}-${c}) at ${pt(cp)} {${esc(c)}};`, `\\draw (${aid}-${c}) -- (${aid});`);
        }
      }
    }
  }
  // relationships
  for (const r of relsHere) {
    const raw = L.rels[r.name];
    const s = Array.isArray(raw) ? { at: raw } : raw;
    const pos = s.at;
    out.push(`\\node[${r.identifying ? 'idrel' : 'rel'}] (${r.name}) at ${pt(pos)} {${esc(r.name)}};`);
    r.ends.forEach(([e, card, part], i) => {
      if (!L.entities[e]) { fail(`${id}: ${r.name} needs ${e} in the diagram`); return; }
      const via = (s.via && s.via[e]) || [];
      const target = (s.anchor && s.anchor[e]) ? `${e}.${s.anchor[e]}` : e;
      const from = (s.from && s.from[e]) ? `${r.name}.${s.from[e]}` : r.name;
      const pts = [`(${from})`, ...via.map(pt), `(${target})`];
      const style = part === 'total' ? 'total' : 'partial';
      const last = pts.length - 2;
      const segs = pts.map((p, k) => k === 0 ? p : `-- ${k - 1 === last ? `node[card,pos=${s.cardpos?.[e] ?? 0.72}] {${card}} ` : ''}${p}`).join(' ');
      out.push(`\\draw[${style}] ${segs};`);
    });
    for (const a of r.attrs) {
      const ap = s.attrs?.[a]; if (!ap) { fail(`${id}: no position for ${r.name}.${a}`); continue; }
      out.push(`\\node[att] (${r.name}-${a}) at ${pt(ap)} {${esc(a)}};`, `\\draw (${r.name}-${a}) -- (${r.name});`);
    }
  }
  out.push('\\end{tikzpicture}');
  return out.join('\n');
}

fs.mkdirSync(outDir, { recursive: true });
for (const [id, L] of Object.entries(LAYOUT.diagrams)) fs.writeFileSync(path.join(outDir, `er-${id}.tex`), diagram(id, L) + '\n');
// relationship table for section 3.2: two relationships per row
const cellsOf = (r) => [`${esc(r.name)}${r.identifying ? '$^{\\ast}$' : ''}`, r.ends.map(e => esc(e[0])).join(' -- '), r.ends.map(e => e[1]).join(':'), r.ends.map(e => e[2] === 'total' ? 'T' : 'P').join('/')];
const half = Math.ceil(RELS.length / 2);
const rows = [];
for (let k = 0; k < half; k++) rows.push([...cellsOf(RELS[k]), ...(RELS[k + half] ? cellsOf(RELS[k + half]) : ['', '', '', ''])].join(' & ') + ' \\\\');
fs.writeFileSync(path.join(outDir, 'rel-table.tex'), rows.join('\n') + '\n');
const entRows = Object.entries(ENTITIES).map(([e, v]) => `${esc(e)} & ${v.module} & \\texttt{${esc(v.table)}} & ${v.weak ? 'weak' : 'strong'} & ${v.attrs.filter(a => a[1] === 'key' || a[1] === 'partial').map(a => (a[1] === 'key' ? '\\underline{' : '\\dashuline{') + esc(a[0]) + '}').join(', ')} \\\\`);
fs.writeFileSync(path.join(outDir, 'entity-table.tex'), entRows.join('\n') + '\n');
// overview: cross-module relationships by module pair, as \ovl<a><b> macros ("NAME 1:N" lines)
const pairs = {};
for (const r of RELS) {
  const ms = modulesOf(r); if (ms.length < 2) continue;
  const key = ms.slice().sort().join('');
  (pairs[key] ??= []).push(`${esc(r.name)} ${r.ends.map(e => e[1]).join(':')}`);
}
const roman = (k) => k.split('').map(n => 'ABCDEF'[n - 1]).join('');
const BS = '\\';
fs.writeFileSync(path.join(outDir, 'overview-labels.tex'), Object.entries(pairs).sort()
  .map(([k, v]) => `${BS}newcommand{${BS}ovl${roman(k)}}{${v.join(BS + BS)}}`).join('\n') + '\n'
  + `${BS}newcommand{${BS}ovcount}{${Object.values(pairs).reduce((n, v) => n + v.length, 0)}}` + '\n');
const entsOf = (m) => Object.entries(ENTITIES).filter(([, v]) => v.module === m).map(([e]) => e.replace(/_/g, BS + 'textunderscore{}')).join(', '); // names do not break
fs.writeFileSync(path.join(outDir, 'overview-modules.tex'), Object.entries(MODULES)
  .map(([m, t]) => `${BS}newcommand{${BS}ovm${'ABCDEF'[m - 1]}}{${BS}textbf{Module ${m}: ${t}}${BS}${BS}[1pt]{${BS}tiny ${entsOf(+m)}}}`).join('\n') + '\n');
console.log(`[er] cross-module relationships by pair: ${Object.entries(pairs).map(([k, v]) => k + '=' + v.length).join(' ')}`);
console.log(`[er] ${Object.keys(ENTITIES).length} entities, ${RELS.length} relationships, ${seen.size} foreign keys; diagrams: ${Object.keys(LAYOUT.diagrams).join(', ')}`);
module.exports = { modulesOf };
